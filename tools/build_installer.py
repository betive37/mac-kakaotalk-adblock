"""Build install.sh from the two maintained Python sources; stdlib only."""

from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path
import textwrap
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ('patch_kakaotalk', 'distribution_entry')

def build_script() -> bytes:
    payload = {name: (ROOT / f'{name}.py').read_text(encoding='utf-8') for name in SOURCES}
    compressed = zlib.compress(
        json.dumps(payload, ensure_ascii=False, separators=(',', ':')).encode('utf-8'), 9,
    )
    encoded = '\n'.join(textwrap.wrap(base64.b64encode(compressed).decode('ascii'), 76))
    digest = hashlib.sha256(compressed).hexdigest()
    template = """#!/bin/sh
# Generated by tools/build_installer.py. Do not edit install.sh directly.
# Requires macOS system tools and Python 3.9+; no package installation.
if ! command -v python3 >/dev/null 2>&1; then
    printf '%s\\n' 'error: Python 3.9 or newer is required (python3 was not found).' >&2
    exit 127
fi
if ! python3 -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 9) else 1)'; then
    printf '%s\\n' 'error: Python 3.9 or newer is required.' >&2
    exit 1
fi
completed=false
trap 'if [ "$completed" != true ]; then printf "%s\\n" "error: incomplete installer script; no patch was applied." >&2; exit 1; fi' 0
python3 - "$@" <<'KAKAOTALK_ADBLOCK_PAYLOAD'
import base64
import hashlib
import json
import sys
import types
import zlib

PAYLOAD = '''__PAYLOAD__'''
try:
    compressed = base64.b64decode(''.join(PAYLOAD.split()), validate=True)
    if hashlib.sha256(compressed).hexdigest() != '__DIGEST__':
        raise ValueError('embedded payload checksum mismatch')
    sources = json.loads(zlib.decompress(compressed).decode('utf-8'))
    if set(sources) != {'patch_kakaotalk', 'distribution_entry'}:
        raise ValueError('embedded module set is invalid')
    if any(not isinstance(source, str) for source in sources.values()):
        raise ValueError('embedded module source is invalid')
except (ValueError, TypeError, UnicodeError, zlib.error) as error:
    print(f'error: incomplete or invalid installer payload: {error}', file=sys.stderr)
    raise SystemExit(1)
for module_name in ('patch_kakaotalk', 'distribution_entry'):
    module = types.ModuleType(module_name)
    module.__file__ = f'<embedded {module_name}.py>'
    sys.modules[module_name] = module
    exec(compile(sources[module_name], module.__file__, 'exec'), module.__dict__)
raise SystemExit(sys.modules['distribution_entry'].distribution_main())
KAKAOTALK_ADBLOCK_PAYLOAD
result=$?
completed=true
trap - 0
exit "$result"
"""
    return template.replace('__PAYLOAD__', encoded).replace('__DIGEST__', digest).encode('utf-8')

def main() -> int:
    destination = ROOT / 'install.sh'
    data = build_script()
    temporary = destination.with_name('.install.sh.tmp')
    try:
        with temporary.open('wb') as stream:
            stream.write(data)
            stream.flush()
        temporary.chmod(0o755)
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)
    return 0

if __name__ == '__main__':
    raise SystemExit(main())
